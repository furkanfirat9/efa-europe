/**
 * Rusça bölge adını temiz Türkçe ada çevirir
 */
export function getTurkishRegionName(ruName: string): string {
  if (!ruName) return '';
  if (RUSSIA_REGION_TR_NAMES[ruName]) return RUSSIA_REGION_TR_NAMES[ruName];
  
  for (const [key, val] of Object.entries(RUSSIA_REGION_TR_NAMES)) {
    if (ruName.includes(key) || key.includes(ruName)) return val;
  }

  return ruName;
}
